"""Self-host the web fonts (Open Sans, Raleway as trimmed variable fonts; Anton as a static display face).

Why: removes the third-party Google Fonts round trips (DNS + TLS + CSS + files),
lets the fonts be preloaded from the first HTML bytes, and is smaller than what
Google serves because the weight axis is limited to what the site uses and only
the needed glyph ranges are kept.

Outputs (committed):
    assets/fonts/<family>-latin.woff2       Basic Latin, Latin-1, typographic punctuation
    assets/fonts/<family>-latin-ext.woff2   Latin Extended-A (Turkish, Central European)
    assets/css/fonts.css                    @font-face rules (minified by `npm run build`)

Needs network access, fontTools and brotli:
    pip install fonttools brotli
    python scripts/build-fonts.py

Only run it when changing fonts, weights or glyph coverage; the build does not.
"""
import io
import os
import re
import urllib.request

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))

# family -> weight range actually used by the site's CSS
FAMILIES = {
    'Open Sans': (300, 700),
    'Raleway': (300, 700),
    # Static display face (single weight, no variable axis): headings in the HUD design.
    'Anton': None,
}

# Unicode ranges (also emitted as `unicode-range`, so a file only downloads
# when a character in its range is rendered).
RANGES = {
    'latin': 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,'
             'U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
    'latin-ext': 'U+0100-0130,U+0132-0151,U+0154-017F',
}

UA = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
                    '(KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36'}


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA)) as r:
        return r.read()


def parse_ranges(spec):
    points = set()
    for part in spec.split(','):
        part = part.strip().lstrip('Uu+')
        lo, _, hi = part.partition('-')
        points.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    return points


def slug(name):
    return name.lower().replace(' ', '-')


def build_family(family, lo, hi):
    if lo is None:
        query = 'family=%s&display=swap' % family.replace(' ', '+')
    else:
        query = 'family=%s:wght@%d..%d&display=swap' % (family.replace(' ', '+'), lo, hi)
    css = fetch('https://fonts.googleapis.com/css2?' + query).decode('utf-8')
    sources = dict(
        (subset_name, url)
        for subset_name, url in re.findall(r'/\* ([\w-]+) \*/\s*@font-face\s*\{[^}]*?url\((https[^)]+)\)', css)
    )
    faces = []
    for subset_name, spec in RANGES.items():
        font = TTFont(io.BytesIO(fetch(sources[subset_name])))

        # Subset first, then limit the weight axis (the other order trips
        # fontTools on glyphs the instancer has lazily dropped).
        opts = subset.Options()
        opts.layout_features = ['*']
        opts.notdef_outline = True
        opts.name_IDs = [1, 2, 3, 4, 6]
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=parse_ranges(spec))
        sub.subset(font)
        if lo is not None:
            font = instancer.instantiateVariableFont(font, {'wght': (lo, hi)})
        font.flavor = 'woff2'

        path = 'assets/fonts/%s-%s.woff2' % (slug(family), subset_name)
        font.save(path)
        print('%-40s %6d bytes' % (path, os.path.getsize(path)))
        weight = '400' if lo is None else '%d %d' % (lo, hi)
        faces.append(
            '@font-face{font-family:"%s";font-style:normal;font-weight:%s;font-display:swap;'
            'src:url("../fonts/%s-%s.woff2") format("woff2");unicode-range:%s}'
            % (family, weight, slug(family), subset_name, spec)
        )
    return faces


if __name__ == '__main__':
    os.makedirs('assets/fonts', exist_ok=True)
    rules = []
    for family, weights in FAMILIES.items():
        lo, hi = weights if weights else (None, None)
        rules += build_family(family, lo, hi)
    with open('assets/css/fonts.css', 'w', encoding='utf-8', newline='') as f:
        f.write('/* Generated by scripts/build-fonts.py - do not edit by hand. */\n' + '\n'.join(rules) + '\n')
    print('wrote assets/css/fonts.css')
